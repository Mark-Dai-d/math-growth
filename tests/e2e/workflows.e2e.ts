test('奖励使用不能超余额，人工纠正需理由，学期评价与大奖可保存', async ({ page }) => {
  await demo(page)
  await navigate(page, '/admin/rewards', '奖励管理')
  await expect(page.locator('.remaining')).toContainText('2.00')
  await page.getByRole('button', { name: '记录使用', exact: true }).click()
  const use = page.getByRole('dialog', { name: '记录奖励使用', exact: true })
  const quantity = use.getByLabel('本次使用数量', { exact: true })
  await quantity.fill('3')
  await use.getByRole('button', { name: '继续确认', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '确认记录奖励使用？', exact: true })).not.toBeVisible()
  expect(await quantity.evaluate((element) => (element as HTMLInputElement).validity.valid)).toBe(false)
  await quantity.fill('1')
  await use.getByLabel('使用备注', { exact: true }).fill('浏览器验收：使用一天')
  await use.getByRole('button', { name: '继续确认', exact: true }).click()
  await confirm(page, '确认记录奖励使用？')
  await expect(page.locator('.remaining')).toContainText('1.00')
  await expect(page.getByRole('row').filter({ hasText: '浏览器验收：使用一天' })).toContainText('-1.00')

  await page.getByRole('button', { name: '人工核实调整', exact: true }).click()
  const adjust = page.getByRole('dialog', { name: '人工核实调整', exact: true })
  await adjust.getByRole('button', { name: '继续确认', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '确认人工调整奖励？', exact: true })).not.toBeVisible()
  const adjustmentReason = adjust.getByLabel('核实与调整原因（必填）', { exact: true })
  expect(await adjustmentReason.evaluate((element) => (element as HTMLTextAreaElement).validity.valid)).toBe(false)
  await adjustmentReason.fill('浏览器验收：补发已核实奖励')
  await adjust.getByRole('button', { name: '继续确认', exact: true }).click()
  await confirm(page, '确认人工调整奖励？')
  await expect(page.locator('.remaining')).toContainText('2.00')
  await expect(page.getByRole('row').filter({ hasText: '浏览器验收：补发已核实奖励' })).toContainText('+1.00')

  await navigate(page, '/admin/summaries', '月度与学期总结')
  await page.getByRole('button', { name: '学期回顾', exact: true }).click()
  const name = '浏览器验收：高一秋季学期'
  await page.getByLabel('学期名称', { exact: true }).fill(name)
  await page.getByRole('button', { name: '填写学期评价', exact: true }).click()
  const semester = page.getByRole('dialog', { name: '学期评价', exact: true })
  await semester.getByLabel('学期评价', { exact: true }).fill('能独立解释函数性质，下一学期继续巩固参数分类。')
  await semester.getByLabel('学期大奖（可留空）', { exact: true }).fill('自主学习成长奖')
  await semester.getByRole('button', { name: '保存评价', exact: true }).click()
  await expect(semester).not.toBeVisible()
  const review = page.locator('.semester-review').filter({ hasText: name })
  await expect(review).toContainText('能独立解释函数性质')
  await expect(review).toContainText('自主学习成长奖')
})
