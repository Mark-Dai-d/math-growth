import { test, expect, type Page } from '@playwright/test'

test.setTimeout(60_000)
const errors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => {
  await page.clock.install({ time: new Date('2026-10-14T12:00:00+08:00') })
  const observed: string[] = []
  errors.set(page, observed)
  page.on('pageerror', (error) => observed.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error') observed.push(`${message.text()} (${message.location().url})`) })
})
test.afterEach(({ page }) => { expect(errors.get(page), '核心操作应无运行或控制台错误').toEqual([]) })

async function navigate(page: Page, path: string, title: string) {
  await page.evaluate((value) => { window.location.hash = value }, path)
  if (path === '/') await expect(page.getByRole('heading', { level: 1 })).toContainText('让每一次理解')
  else await expect(page.getByRole('heading', { name: title, exact: true })).toBeVisible()
}

async function demo(page: Page) {
  await page.goto('/#/')
  await page.getByRole('button', { name: '体验演示工作台' }).click()
  await expect(page.getByRole('heading', { name: '学习概览', exact: true })).toBeVisible()
}

async function confirm(page: Page, title: string) {
  const dialog = page.getByRole('dialog', { name: title, exact: true })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('button', { name: '确认操作', exact: true }).click()
  await expect(dialog).not.toBeVisible()
}

test('规则权重必须合计10分，新版本保留历史，考试按得分率与可比性加分', async ({ page }) => {
  await demo(page)
  await navigate(page, '/admin/rules', '规则版本管理')
  await page.getByRole('button', { name: '创建新版本', exact: true }).click()
  await page.getByLabel('生效日期', { exact: true }).fill('2026-11-01')
  const weights = page.getByLabel('满分权重', { exact: true })
  await weights.nth(0).fill('4')
  await expect(page.locator('.weights-summary')).toContainText('11.00 / 10')
  await expect(page.getByRole('button', { name: '保存新版本', exact: true })).toBeDisabled()
  await weights.nth(1).fill('2')
  await expect(page.locator('.weights-summary')).toContainText('10.00 / 10')
  await page.getByRole('button', { name: '保存新版本', exact: true }).click()
  await confirm(page, '创建新的规则版本？')
  const version2 = page.locator('.version-item').filter({ hasText: '规则 v2' })
  await expect(version2).toContainText('计划生效')
  await version2.click()
  await expect(weights.nth(0)).toHaveValue('4')
  await expect(weights.nth(0)).toBeDisabled()
  await page.locator('.version-item').filter({ hasText: '规则 v1' }).click()
  await expect(weights.nth(0)).toHaveValue('3')

  await navigate(page, '/admin/exams', '考试成绩')
  const bonus = page.locator('.metric').filter({ hasText: '本月考试额外加分' })
  await expect(bonus.locator('.metric-value')).toContainText('0.00')
  await page.getByRole('button', { name: '录入考试', exact: true }).click()
  const editor = page.getByRole('dialog', { name: '录入考试成绩', exact: true })
  const examName = '浏览器验收：百分制进步考试'
  await editor.getByLabel('考试名称', { exact: true }).fill(examName)
  await editor.getByLabel('考试满分', { exact: true }).fill('100')
  await editor.getByLabel('原始成绩', { exact: true }).fill('86')
  const comparable = editor.getByLabel('我已确认两次考试范围与难度合理可比')
  await expect(comparable).toBeDisabled()
  const comparison = editor.getByLabel('对比考试')
  const baseline = await comparison.locator('option').filter({ hasText: '2026-09-27' }).getAttribute('value')
  if (!baseline) throw new Error('缺少 114 / 150 的对比考试')
  await comparison.selectOption(baseline)
  await editor.getByRole('button', { name: '保存考试', exact: true }).click()
  await expect(editor).not.toBeVisible()
  const examRow = page.getByRole('row').filter({ hasText: examName })
  await expect(examRow).toContainText('86.00%')
  await expect(examRow).toContainText('未确认')
  await expect(bonus.locator('.metric-value')).toContainText('0.00')
  await examRow.getByRole('button', { name: `编辑 ${examName}`, exact: true }).click()
  const edit = page.getByRole('dialog', { name: '编辑考试成绩', exact: true })
  await edit.getByLabel('我已确认两次考试范围与难度合理可比').check()
  await expect(edit.getByText(/得分率变化：\+10.00 个百分点/)).toBeVisible()
  await edit.getByRole('button', { name: '保存考试', exact: true }).click()
  await confirm(page, '确认修改考试成绩？')
  await expect(examRow).toContainText('已确认')
  await expect(bonus.locator('.metric-value')).toContainText('1.00')
})

