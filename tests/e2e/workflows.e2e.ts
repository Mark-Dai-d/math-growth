  await history.getByRole('button', { name: '关闭', exact: true }).click()

  await page.getByRole('button', { name: '发布匿名结果', exact: true }).click()
  await confirm(page, '发布匿名月度结果？')
  await expect(page.locator('.settlement-detail')).toContainText('已发布匿名结果')
  await navigate(page, '/', '让每一次理解，都成为进步。')
  await expect(page.locator('.public-history').getByText('2026-09', { exact: true })).toBeVisible()
